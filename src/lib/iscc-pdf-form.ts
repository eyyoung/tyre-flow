type TextFieldMap = Record<string, (data: IsccFormData) => string>;
type CheckBoxMap = Record<string, (data: IsccFormData) => boolean>;
/** 签名图位置：用表单里的某个字段矩形，或直接给页面坐标（pt，左下角原点） */
type SignaturePlacement =
  | { field: string }
  | { page: number; x: number; y: number; height: number; maxWidth: number };

interface IsccFormLayout {
  text: TextFieldMap;
  checkboxes: CheckBoxMap;
  /**
   * 「下划线填空」类字段：官方表单里这些字段的矩形比一行字高得多（底边就是下划线），
   * pdf-lib 会把文字垂直居中，看起来浮在下划线上方。列在这里的字段改为贴着下划线排（见 alignToBaseline）。
   */
  baselineFields?: string[];
  signature: SignaturePlacement;
}

/** 文本字段默认字号；单行字段放不下时按比例缩小（0.5pt 步进），与 Chrome 里手填的自动缩小效果一致 */
const FIELD_FONT_SIZE = 10;
const MIN_FONT_SIZE = 4;
/** 签名图高度（pt）。原 docx 方案里图片模块按 96dpi 的 40px 输出，即 30pt */

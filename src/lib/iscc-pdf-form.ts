/** 单行字段左右各留的内边距 */
const FIELD_PADDING = 4;
/** 贴下划线排的字段统一改成这么高的一行 */
const BASELINE_FIELD_HEIGHT = 14;
/** 文字基线抬到下划线（原矩形底边）之上多少 pt；官方表单里相邻正文的基线也在底边上方约 1pt */
const BASELINE_LIFT = 1;


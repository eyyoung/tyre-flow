let helveticaCharset: Set<number> | null = null;

function getHelveticaCharset(font: PDFFont): Set<number> {
  if (!helveticaCharset) helveticaCharset = new Set(font.getCharacterSet());
  return helveticaCharset;
}

/**
 * 把文本变成表单字体（Helvetica / WinAnsi）能表示的形式：
 * 汉字转拼音（每个音节首字母大写），其余不可编码字符丢弃。
 */
export function toLatinText(value: string, charset: Set<number>): string {
  const transliterated = value.replace(/[㐀-鿿]+/g, (han) =>
    pinyin(han, { toneType: "none", type: "array" })
      .map((syllable) => syllable.charAt(0).toUpperCase() + syllable.slice(1))
      .join("")
  );
  let result = "";
  for (const char of transliterated) {
    const codePoint = char.codePointAt(0) ?? 0;
    if (charset.has(codePoint)) result += char;
  }
  return result.replace(/\s{2,}/g, " ").trim();
}

function findWidgetPage(pdf: PDFDocument, field: PDFField): number {
  const widget = field.acroField.getWidgets()[0];
  if (!widget) throw new Error(`Field "${field.getName()}" has no widget`);
  const widgetRef = pdf.context.getObjectRef(widget.dict);
  const pages = pdf.getPages();
  for (let index = 0; index < pages.length; index++) {
    const annots = pages[index].node.Annots();
    if (!annots) continue;
    if (annots.asArray().some((ref) => ref === widgetRef)) return index;
  }
  throw new Error(`Field "${field.getName()}" is not placed on any page`);
}

/**
 * pdf-lib 拍平后，页面 /Annots 里可能残留指向已删除控件的引用
 * （对 pdf-lib 自己创建的字段必现），poppler 会报 XRef 错误并拒绝渲染后续对象。
 */
function pruneDanglingAnnotations(pdf: PDFDocument): void {
  for (const page of pdf.getPages()) {
    const annots = page.node.Annots();
    if (!annots) continue;
    const kept = annots
      .asArray()
      .filter((ref) => !(ref instanceof PDFRef) || pdf.context.lookup(ref) !== undefined);
    if (kept.length !== annots.size()) {
      page.node.set(PDFName.of("Annots"), pdf.context.obj(kept));
    }
  }
}

/** 单行字段的字号：默认 FIELD_FONT_SIZE，放不下时按比例缩小 */
function fitFontSize(font: PDFFont, text: string, fieldWidth: number): number {
  const available = fieldWidth - FIELD_PADDING * 2;
  const natural = font.widthOfTextAtSize(text, FIELD_FONT_SIZE);
  if (natural <= available) return FIELD_FONT_SIZE;
  return Math.max(MIN_FONT_SIZE, Math.floor(((FIELD_FONT_SIZE * available) / natural) * 2) / 2);
}

/**
 * 把字段矩形改成一行高，并让文字基线落在原矩形底边（下划线）上方 BASELINE_LIFT pt。
 * pdf-lib 单行文字的基线 = rect.y + rect.height / 2 - 字体高度（不含下伸部）/ 2，与边框、内边距无关。
 */
function alignToBaseline(field: PDFTextField, font: PDFFont, fontSize: number): void {
  const widget = field.acroField.getWidgets()[0];
  const rect = widget.getRectangle();
  const glyphHeight = font.heightAtSize(fontSize, { descender: false });
  const baseline = rect.y + BASELINE_LIFT;
  widget.setRectangle({
    x: rect.x,
    y: baseline - BASELINE_FIELD_HEIGHT / 2 + glyphHeight / 2,
    width: rect.width,
    height: BASELINE_FIELD_HEIGHT,
  });
}

function fillTextFields(form: PDFForm, layout: IsccFormLayout, data: IsccFormData, font: PDFFont): void {
  const charset = getHelveticaCharset(font);
  const baselineFields = new Set(layout.baselineFields);
  for (const [fieldName, getValue] of Object.entries(layout.text)) {
    const field = form.getTextField(fieldName);
    const value = toLatinText(getValue(data), charset);
    field.setText(value);
    let fontSize = FIELD_FONT_SIZE;
    if (!field.isMultiline()) {
      const width = field.acroField.getWidgets()[0]?.getRectangle().width ?? 0;
      fontSize = fitFontSize(font, value, width);
    }
    field.setFontSize(fontSize);
    if (baselineFields.has(fieldName)) alignToBaseline(field, font, fontSize);
    field.updateAppearances(font);
  }
}

function fillCheckBoxes(form: PDFForm, layout: IsccFormLayout, data: IsccFormData): void {
  for (const [fieldName, isChecked] of Object.entries(layout.checkboxes)) {
    const checkBox = form.getCheckBox(fieldName);
    if (isChecked(data)) checkBox.check();
    else checkBox.uncheck();
  }
}

function resolveSignatureRect(
  pdf: PDFDocument,
  form: PDFForm,
  placement: SignaturePlacement
): { page: number; x: number; y: number; height: number; maxWidth: number } {
  if (!("field" in placement)) return placement;
  const field = form.getField(placement.field);
  const page = findWidgetPage(pdf, field);
  const rect = field.acroField.getWidgets()[0].getRectangle();
  // 签名域只用来定位，拍平前移除（签名域本身不能拍平）
  form.removeField(field);
  return { page, x: rect.x, y: rect.y, height: Math.min(rect.height, SIGNATURE_HEIGHT), maxWidth: rect.width };
}

async function drawSignature(
  pdf: PDFDocument,
  rect: { page: number; x: number; y: number; height: number; maxWidth: number },
  imageBytes: Uint8Array
): Promise<void> {
  const isPng =
    imageBytes.length > 4 &&
    imageBytes[0] === 0x89 &&
    imageBytes[1] === 0x50 &&
    imageBytes[2] === 0x4e &&
    imageBytes[3] === 0x47;
  const image = isPng ? await pdf.embedPng(imageBytes) : await pdf.embedJpg(imageBytes);
  let height = rect.height;
  let width = (image.width * height) / image.height;
  if (width > rect.maxWidth) {
    width = rect.maxWidth;
    height = (image.height * width) / image.width;
  }
  pdf.getPage(rect.page).drawImage(image, { x: rect.x, y: rect.y, width, height });
}

/**
 * 用一份门店数据填充 ISCC 表单模板，返回拍平后的 PDF 字节。
 */
export async function fillIsccForm(
  templateBytes: Uint8Array,
  templateKey: IsccTemplateKey,
  data: IsccFormData,
  signatureImage: Uint8Array | null
): Promise<Uint8Array> {
  const layout = FORM_LAYOUTS[templateKey];
  const pdf = await PDFDocument.load(templateBytes);
  const form = pdf.getForm();
  const font = await pdf.embedFont(StandardFonts.Helvetica);

  fillTextFields(form, layout, data, font);
  fillCheckBoxes(form, layout, data);
  const signatureRect = resolveSignatureRect(pdf, form, layout.signature);

  form.flatten();
  pruneDanglingAnnotations(pdf);
  // 签名在拍平之后再画，确保盖在字段外观之上
  if (signatureImage) await drawSignature(pdf, signatureRect, signatureImage);

  return pdf.save();
}

/** 把多份 PDF 按顺序合并成一份 */
export async function mergePdfDocuments(documents: Uint8Array[]): Promise<Uint8Array> {
  if (documents.length === 1) return documents[0];
  const merged = await PDFDocument.create();
  for (const bytes of documents) {
    const source = await PDFDocument.load(bytes);
    const pages = await merged.copyPages(source, source.getPageIndices());
    for (const page of pages) merged.addPage(page);
  }
  return merged.save();
}
